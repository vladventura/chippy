fontset = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, #0
    0x20, 0x60, 0x20, 0x20, 0x70, #1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, #2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, #3
    0x90, 0x90, 0xF0, 0x10, 0x10, #4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, #5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, #6
    0xF0, 0x10, 0x20, 0x40, 0x40, #7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, #8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, #9
    0xF0, 0x90, 0xF0, 0x90, 0x90, #A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, #B
    0xF0, 0x80, 0x80, 0x80, 0xF0, #C
    0xE0, 0x90, 0x90, 0x90, 0xE0, #D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, #E
    0xF0, 0x80, 0xF0, 0x80, 0x80  #F
]

def initialize_memory():
    load_fontset()

def load_program(prog):
    global memory
    chunks = []
    with open(prog, 'rb') as binf:
        while True:
            chunk = binf.read(1)
            if not chunk: break
            if len(chunk) == 1:
                chunks.append(int.from_bytes(chunk, byteorder='big'))
    counter = 0x200
    for chunk in chunks:
        memory[counter] = chunk
        counter += 1

def load_fontset():
    global fontset, memory
    for font in range(len(fontset)):
        memory[font] = fontset[font]

def memory_read(addr) -> int:
    global memory
    return memory[addr]

def memory_write(addr, val):
    global memory
    memory[addr] = val
